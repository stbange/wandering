def obj(name, vertices, faces):
    lines = ['# Original Wandering Castle mesh; CC BY 4.0']
    lines += [f'v {x} {y} {z}' for x,y,z in vertices]
    lines += ['f ' + ' '.join(str(i+1) for i in face) for face in faces]
    (ROOT / 'meshes' / (name + '.obj')).write_text('\n'.join(lines)+'\n')

